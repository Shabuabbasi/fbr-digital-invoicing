import PDFDocument from "pdfkit";
import type { Response } from "express";
import type { InvoiceDocument } from "../../models/Invoice";
import type { HydratedDocument } from "mongoose";

function formatMoney(minorUnits: number): string {
  return `PKR ${(minorUnits / 100).toLocaleString("en-PK", { minimumFractionDigits: 2 })}`;
}

export function streamInvoicePdf(invoice: HydratedDocument<InvoiceDocument>, res: Response): void {
  const doc = new PDFDocument({ size: "A4", margin: 50 });

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${invoice.invoiceNumber}.pdf"`);
  doc.pipe(res);

  doc.fontSize(16).text("Intelgency IT Solutions", { continued: false });
  doc.fontSize(10).fillColor("#666").text("Intelgency Digital Invoicing");
  doc.moveDown();

  doc.fillColor("#000").fontSize(14).text(`Invoice ${invoice.invoiceNumber}`);
  doc.fontSize(10).fillColor("#666").text(new Date(invoice.invoiceDate).toLocaleDateString());
  if (invoice.fbrReferenceNumber) {
    doc.text(`FBR Reference: ${invoice.fbrReferenceNumber}`);
  }
  doc.moveDown();

  const colWidth = 250;
  const sellerY = doc.y;
  doc.fillColor("#000").fontSize(10).text("Seller", 50, sellerY, { width: colWidth, underline: true });
  doc.text(invoice.sellerSnapshot.name, 50, doc.y);
  if (invoice.sellerSnapshot.ntn) doc.text(`NTN: ${invoice.sellerSnapshot.ntn}`, 50);
  if (invoice.sellerSnapshot.address) doc.text(invoice.sellerSnapshot.address, 50);

  doc.text("Bill To", 300, sellerY, { width: colWidth, underline: true });
  doc.text(invoice.buyerSnapshot.name, 300, doc.y < sellerY + 12 ? sellerY + 12 : doc.y);
  if (invoice.buyerSnapshot.ntn) doc.text(`NTN: ${invoice.buyerSnapshot.ntn}`, 300);
  if (invoice.buyerSnapshot.address) doc.text(invoice.buyerSnapshot.address, 300);

  doc.moveDown(2);

  const tableTop = doc.y;
  doc.fontSize(9).fillColor("#666");
  doc.text("Item", 50, tableTop, { width: 160 });
  doc.text("Qty", 210, tableTop, { width: 40 });
  doc.text("Unit Price", 250, tableTop, { width: 80 });
  doc.text("Tax", 330, tableTop, { width: 70 });
  doc.text("Total", 470, tableTop, { width: 80, align: "right" });
  doc.moveTo(50, tableTop + 14).lineTo(550, tableTop + 14).strokeColor("#ddd").stroke();

  let y = tableTop + 20;
  doc.fillColor("#000");
  for (const item of invoice.items) {
    doc.fontSize(9);
    doc.text(item.productName, 50, y, { width: 160 });
    doc.text(String(item.quantity), 210, y, { width: 40 });
    doc.text(formatMoney(item.unitPriceMinor), 250, y, { width: 80 });
    doc.text(formatMoney(item.taxMinor), 330, y, { width: 70 });
    doc.text(formatMoney(item.lineTotalMinor), 470, y, { width: 80, align: "right" });
    y += 18;
  }

  doc.moveTo(50, y + 4).lineTo(550, y + 4).strokeColor("#ddd").stroke();
  y += 14;

  doc.fontSize(9).fillColor("#666").text("Subtotal", 400, y, { width: 100 });
  doc.fillColor("#000").text(formatMoney(invoice.subtotalMinor), 470, y, { width: 80, align: "right" });
  y += 16;
  doc.fillColor("#666").text("Discount", 400, y, { width: 100 });
  doc.fillColor("#000").text(`-${formatMoney(invoice.discountMinor)}`, 470, y, { width: 80, align: "right" });
  y += 16;
  doc.fillColor("#666").text("Tax", 400, y, { width: 100 });
  doc.fillColor("#000").text(formatMoney(invoice.taxMinor), 470, y, { width: 80, align: "right" });
  y += 18;
  doc.fontSize(11).fillColor("#000").text("Total", 400, y, { width: 100 });
  doc.text(formatMoney(invoice.totalMinor), 470, y, { width: 80, align: "right" });

  doc
    .fontSize(8)
    .fillColor("#999")
    .text("Generated by Intelgency Digital Invoicing — Intelgency IT Solutions", 50, 780, {
      width: 500,
      align: "center",
    });

  doc.end();
}
